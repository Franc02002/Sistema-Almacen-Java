-- 1. Tabla PRODUCTO: Catálogo identificado por código de barras (EAN-13/EAN-8)
CREATE TABLE IF NOT EXISTS PRODUCTO (
    codigo_barras VARCHAR(50) NOT NULL PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    categoria VARCHAR(60) NOT NULL,
    precio_unitario DECIMAL(12, 2) NOT NULL,
    stock_actual INTEGER NOT NULL,
    stock_minimo INTEGER DEFAULT 5 NOT NULL,
    activo BOOLEAN DEFAULT TRUE NOT NULL
);

-- 2. Tabla VENTA: Cabecera transaccional de cada ticket emitido en el Punto de Venta
CREATE TABLE IF NOT EXISTS VENTA (
    id_venta INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) PRIMARY KEY,
    fecha_hora TIMESTAMP NOT NULL,
    monto_total DECIMAL(12, 2) NOT NULL,
    cantidad_items INTEGER NOT NULL,
    metodo_pago VARCHAR(40) DEFAULT 'EFECTIVO' NOT NULL
);

-- 3. Tabla DETALLE_VENTA: Renglones que conforman cada venta (Relación 1:N con VENTA y N:1 con PRODUCTO)
CREATE TABLE IF NOT EXISTS DETALLE_VENTA (
    id_detalle INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) PRIMARY KEY,
    id_venta INTEGER NOT NULL,
    codigo_barras VARCHAR(50) NOT NULL,
    cantidad INTEGER NOT NULL,
    precio_unitario_historico DECIMAL(12, 2) NOT NULL,
    subtotal DECIMAL(12, 2) NOT NULL,
    CONSTRAINT fk_detalle_venta FOREIGN KEY (id_venta) REFERENCES VENTA(id_venta) ON DELETE CASCADE,
    CONSTRAINT fk_detalle_producto FOREIGN KEY (codigo_barras) REFERENCES PRODUCTO(codigo_barras)
);

-- 4. Tabla MOVIMIENTO_STOCK: Auditoría de ingresos de stock (Manual o por Planilla Excel)
CREATE TABLE IF NOT EXISTS MOVIMIENTO_STOCK (
    id_movimiento INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) PRIMARY KEY,
    codigo_barras VARCHAR(50) NOT NULL,
    fecha_hora TIMESTAMP NOT NULL,
    cantidad_agregada INTEGER NOT NULL,
    origen VARCHAR(30) NOT NULL,
    observacion VARCHAR(200),
    CONSTRAINT fk_movimiento_producto FOREIGN KEY (codigo_barras) REFERENCES PRODUCTO(codigo_barras)
);
